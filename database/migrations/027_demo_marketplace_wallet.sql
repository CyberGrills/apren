CREATE TABLE seven.demo_wallets (
  user_id uuid PRIMARY KEY REFERENCES seven.users(user_id) ON DELETE CASCADE,
  currency_code char(3) NOT NULL DEFAULT 'NGN' CHECK (currency_code='NGN'),
  balance_minor numeric(20,0) NOT NULL DEFAULT 50000000000 CHECK (balance_minor >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE seven.demo_bookings (
  booking_id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES seven.users(user_id) ON DELETE CASCADE,
  item_id text NOT NULL REFERENCES seven.demo_catalog_items(item_id),
  kind varchar(16) NOT NULL CHECK (kind IN ('STAY','DINING','EXPERIENCE')),
  item_title varchar(180) NOT NULL,
  city varchar(100) NOT NULL,
  start_date date NOT NULL,
  end_date date,
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 20),
  unit_price_minor bigint NOT NULL CHECK (unit_price_minor > 0),
  total_minor numeric(20,0) NOT NULL CHECK (total_minor > 0),
  status varchar(16) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED','CANCELLED')),
  reference varchar(40) NOT NULL UNIQUE,
  idempotency_key varchar(200) NOT NULL,
  payload_hash char(64) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  cancelled_at timestamptz,
  UNIQUE(user_id,idempotency_key)
);
CREATE INDEX demo_bookings_user_created_idx ON seven.demo_bookings(user_id,created_at DESC);
CREATE TABLE seven.demo_wallet_entries (
  entry_id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES seven.users(user_id) ON DELETE CASCADE,
  booking_id uuid REFERENCES seven.demo_bookings(booking_id),
  entry_type varchar(12) NOT NULL CHECK (entry_type IN ('INITIAL_CREDIT','DEBIT','REFUND')),
  amount_minor numeric(20,0) NOT NULL CHECK (amount_minor > 0),
  balance_after_minor numeric(20,0) NOT NULL CHECK (balance_after_minor >= 0),
  reference varchar(60) NOT NULL UNIQUE,
  idempotency_key varchar(200) NOT NULL,
  description varchar(240) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id,idempotency_key)
);
CREATE INDEX demo_wallet_entries_user_created_idx ON seven.demo_wallet_entries(user_id,created_at DESC);
